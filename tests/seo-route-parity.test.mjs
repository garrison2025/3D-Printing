import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const build=fs.readFileSync(new URL('../scripts/build.mjs',import.meta.url),'utf8');
const staticAudit=fs.readFileSync(new URL('../scripts/audit.mjs',import.meta.url),'utf8');
const liveAudit=fs.readFileSync(new URL('../scripts/seo-live-audit.mjs',import.meta.url),'utf8');
const keywordMap=JSON.parse(fs.readFileSync(new URL('../src/content/keyword-intent-map.json',import.meta.url),'utf8'));
const routes=(source,pattern,name)=>{
 const part=source.match(pattern)?.[1];
 assert.ok(part,'Missing route list: '+name);
 const list=[...part.matchAll(/'([^']+)'/g)].map(m=>m[1]);
 assert.equal(new Set(list).size,list.length,'Duplicate '+name+' route');
 return list;
};
test('production sitemap and both SEO validators inspect the exact same set of thirteen real pages',()=>{
 const built=routes(build,/const pages=\[([^\]]+)\];/,'build sitemap');
 const audited=routes(staticAudit,/const routes=\[([^\]]+)\];/,'static SEO audit');
 const live=routes(liveAudit,/const ROUTES=\[([\s\S]*?)\];/,'live SEO audit');
 assert.equal(built.length,13);
 assert.deepEqual([...audited].sort(),[...built].sort());
 assert.deepEqual([...live].sort(),[...built].sort());
});
test('every prioritized keyword is routed to a page actually generated by the site builder',()=>{
 const built=new Set(routes(build,/const pages=\[([^\]]+)\];/,'build sitemap'));
 const prioritized=keywordMap.keywords.filter(x=>['P0','P1','P2'].includes(x.priority));
 assert.equal(prioritized.length,94);
 for(const row of prioritized)assert.ok(built.has(row.destination),row.keyword+' points to a non-published canonical '+row.destination);
});
test('Cloudflare Pages protects both named and version preview aliases even on a production build',()=>{
 for(const hostname of [
  'https://3d-printing-1r7.pages.dev/*',
  'https://:version.3d-printing-1r7.pages.dev/*'
 ])assert.ok(build.includes(hostname),hostname);
 assert.match(build,/X-Robots-Tag: noindex/);
 assert.match(build,/const pages=\[/);
});
